const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const logo = JSON.parse(fs.readFileSync(path.join(root, 'brand/desk-logo.json'), 'utf8'));
const [a,b,c,d,e,f] = logo.projection;
function project(source) {
  // The canonical waveform uses absolute M/C commands and coordinate pairs.
  return source.replace(/([MC])([^MCZ]+)/g, (_,command,coords) => {
    const values = coords.match(/-?(?:\d*\.)?\d+/g).map(Number);
    return command + values.map((v,i) => i % 2 ? null : [a*v+c*values[i+1]+e,b*v+d*values[i+1]+f].map(n=>+n.toFixed(3)).join(',')).filter(v=>v!==null).join(' ') + ' ';
  });
}
const wave = project(logo.wave);
const mark = `<path android:fillColor="#999999" android:pathData="${logo.side}"/>
    <path android:fillColor="#FFFFFF" android:pathData="${logo.legs}"/>
    <path android:fillColor="#FFFFFF" android:fillType="evenOdd" android:pathData="${logo.top} ${wave}"/>`;
const files = {
  'app/src/main/res/drawable/ic_launcher.xml': `<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="128dp" android:height="128dp" android:viewportWidth="128" android:viewportHeight="128">
    <path android:fillColor="#000000" android:pathData="M0 0 H128 V128 H0 Z"/>
    ${mark}
</vector>\n`,
  'app/src/main/res/drawable/desk_foreground.xml': `<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="108dp" android:height="108dp" android:viewportWidth="128" android:viewportHeight="128">
    <group android:pivotX="64" android:pivotY="64" android:scaleX="0.8" android:scaleY="0.8">
    ${mark}
    </group>
</vector>\n`,
  'app/src/main/java/com/balnc/audioddesk/DeskLogoPaths.kt': `// Generated by scripts/generate-brand.cjs from brand/desk-logo.json.
package com.balnc.audioddesk

internal object DeskLogoPaths {
    const val TOP = "${logo.top}"
    const val SIDE = "${logo.side}"
    const val LEGS = "${logo.legs}"
    const val WAVE = "${logo.wave}"
    val PROJECTION = floatArrayOf(${[a,c,e,b,d,f,0,0,1].map(n=>`${n}f`).join(', ')})
    const val CYCLE_MS = ${logo.cycleMs}L
}
`
};
for (const [name,content] of Object.entries(files)) {
  const target = path.join(root,name);
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(target) || fs.readFileSync(target,'utf8')!==content) throw Error(`Regenerate brand asset: ${name}`);
  } else {
    fs.mkdirSync(path.dirname(target),{recursive:true});
    fs.writeFileSync(target,content);
  }
}
console.log(process.argv.includes('--check') ? 'Brand assets match canonical logo' : 'Generated desk launcher and animation paths');
